import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync,rmSync,writeFileSync,readFileSync,symlinkSync,mkdirSync} from 'node:fs';
import {createHash} from 'node:crypto';
import os from 'node:os';import path from 'node:path';
import {createBootstrapRuntime} from '../bootstrap/runtime.mjs';
import {createControlDispatcher} from '../control/dispatcher.mjs';
import {createWorkstationFilePort,FILE_READ,FILE_INSPECT,DIR_LIST,DIR_CREATE,FILE_WRITE,FILE_EDIT} from '../control/workstation-file-port.mjs';
const hash=b=>createHash('sha256').update(b).digest('hex'),owner={source:'desktop',actor:'desktop-owner'},approval={channel:'desktop-owner-token',actor:'desktop-owner'};
test('native file operations default closed',()=>assert.throws(()=>createWorkstationFilePort({env:{}}).read(FILE_READ,{root_id:'repo',path:'a'}),/WORKSTATION_FILE_DISABLED/));
test('real native scoped files: journal, read/list, create/write/edit, stale and escape denial',{skip:!process.env.VIVIM_WORKSTATION_FILES_EXE,timeout:90000},async t=>{
 const root=mkdtempSync(path.join(os.tmpdir(),'vivim-files-')),workspace=path.join(root,'workspace'),config=path.join(root,'roots.json');mkdirSync(workspace);
 const outside=path.join(root,'outside');mkdirSync(outside);writeFileSync(path.join(outside,'outside.txt'),'not granted');
 const exe=process.env.VIVIM_WORKSTATION_FILES_EXE;
 writeFileSync(config,JSON.stringify({schema:'vivim.workstation-roots/1',roots:[{id:'repo',path:workspace}]}));
 const env={VIVIM_WORKSTATION_ROOTS:config,VIVIM_WORKSTATION_ROOTS_SHA256:hash(readFileSync(config)),VIVIM_WORKSTATION_FILES_EXE:exe,VIVIM_WORKSTATION_FILES_SHA256:hash(readFileSync(exe))};
 const runtime=createBootstrapRuntime({dataRoot:root,file:':memory:'}),filePort=createWorkstationFilePort({env}),control=createControlDispatcher({dataRoot:root,runtime,workstationFile:filePort});
 t.after(()=>{runtime.close();try{rmSync(root,{recursive:true,force:true})}catch{}});
 const args=(p,extra={})=>({root_id:'repo',path:p,...extra});
 const plan=(actionId,a)=>control.plan({actionId,args:a},owner);
 const apply=async(actionId,a)=>{const p=plan(actionId,a);assert.equal(p.outcome,'approval_required');const r=await control.execute({planId:p.planId,planDigest:p.planDigest,approval});assert.equal(r.status,'applied',JSON.stringify(r.error));return r;};
 const read=(actionId,a)=>{const r=plan(actionId,a);assert.equal(r.outcome,'done');return r.result;};
 assert.equal(control.plan({actionId:DIR_LIST,args:args('.')},{source:'mobile'}).outcome,'unavailable');
 await apply(DIR_CREATE,args('src'));
 const created=await apply(FILE_WRITE,args('src/hello.txt',{expected_digest:'absent',content:'á\r\nHello\r\n'}));
 const first=read(FILE_READ,args('src/hello.txt'));assert.equal(first.text,'á\r\nHello\r\n');assert.equal(first.digest,created.result.afterDigest);
 assert.equal(read(FILE_INSPECT,args('src/hello.txt')).digest,first.digest);assert.equal(read(DIR_LIST,args('src')).entries[0].name,'hello.txt');
 const edit=await apply(FILE_EDIT,args('src/hello.txt',{expected_digest:first.digest,old_text:'Hello',new_text:'VIVIM'}));
 assert.equal(read(FILE_READ,args('src/hello.txt')).text,'á\r\nVIVIM\r\n');
 assert.equal(edit.result.afterDigest,hash('á\r\nVIVIM\r\n'));
 assert.throws(()=>plan(FILE_WRITE,args('src/hello.txt',{expected_digest:first.digest,content:'stale'})),/STALE_DIGEST/);
 assert.throws(()=>read(FILE_READ,args('../outside/outside.txt')),/PATH_INVALID/);
 assert.throws(()=>read(FILE_READ,args('C:/outside.txt')),/PATH_INVALID/);
 assert.throws(()=>read(FILE_READ,{root_id:'unknown',path:'x'}),/ROOT_NOT_GRANTED/);
 symlinkSync(outside,path.join(workspace,'escape'),process.platform==='win32'?'junction':'dir');
 assert.throws(()=>read(FILE_READ,args('escape/outside.txt')),/PATH_ESCAPE/);
 const stale=plan(FILE_WRITE,args('src/hello.txt',{expected_digest:edit.result.afterDigest,content:'new'}));
 writeFileSync(path.join(workspace,'src','hello.txt'),'external');
 assert.throws(()=>control.execute({planId:stale.planId,planDigest:stale.planDigest,approval}),/STALE_DIGEST/);
 assert.equal(readFileSync(path.join(workspace,'src','hello.txt'),'utf8'),'external');
 assert.equal(control.status(stale.planId).state,'planned');
 console.log('NATIVE_FILE_RECEIPT='+JSON.stringify({planId:edit.planId,status:edit.status,readback:true,scopeEscapeDenied:true,staleDenied:true}));
});
