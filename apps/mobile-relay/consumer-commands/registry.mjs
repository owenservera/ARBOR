// ---------- export helpers ----------
export function commandById(id) { return COMMANDS.find(c => c.id === id) || null; }
export function signalById(id) { return SIGNALS.find(s => s.id === id) || null; }
export function commandsByConsumer(consumer) { return COMMANDS.filter(c => c.consumer === consumer); }
export function commandsByKind(kind) { return COMMANDS.filter(c => c.kind === kind); }
export function commandsByScope(scope) { return COMMANDS.filter(c => c.scope === scope); }
export function allCommandIds() { return COMMANDS.map(c => c.id); }
export function allSignalIds() { return SIGNALS.map(s => s.id); }
