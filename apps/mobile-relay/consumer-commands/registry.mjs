// P1 startup assertion: every registry entry that behaves as a bootstrap command
// must be a member of the canonical allowlist. A drift fails fast at import time.
for (const entry of COMMANDS) {
  if (entry.mode === 'bootstrap' && !BOOTSTRAP_ACTION_SET.has(entry.id)) {
    throw new Error(`consumer-command registry: bootstrap-mode command '${entry.id}' is not in the canonical bootstrap allowlist`);
  }
}

