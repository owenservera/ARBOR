// VIVIM consumer-command + signal registry (v1).
// Centralized, single source of truth for every command and signal that is
// truly unique to a consumer app (the phone/PWA harness), distinct from the
// Host bootstrap command surface. Maximal reprogrammability: every entry is
// declarative data with id, kind, consumer, action, scope, inputs, outputs,
// and a reprogrammable handler hook reference.
//
// Design rules:
// - No executable code lives here. This is pure data + a small validator.
// - Consumers: harness (chat), bootstrap (personalization), grokbot (fleet),
//   control (system), iconographic (new icon delivery/customization system).
// - Every command carries `consumer`, `mode`, `kind`, `action`, `scope` so it
//   can be routed, audited, revoked, and regenerated on command.
// - Signals are the user-visible input modalities that trigger commands.
// - This file is regenerated by the harness "on command" from this registry.
//
// EXISTING surface (preserved, anchored):
//   app.js            -> commands: pair, commands(relay-chat), phone prompt
//   bridge-commands   -> CONSUMERS [grokbot,harness,bootstrap], KINDS [command,intent,stage]
//   command-worker    -> BOOTSTRAP_ACTIONS [grant-visual,choose-preset,undo-theme,undo-ui-revision,apply-proposal,personalize]
//   control-phone     -> api/control/plan (text -> plan, preview only)
//   catalog.mjs       -> GUI01 ops [insert,remove,move,replace-props,set-theme], button intents
//   semantic-projection-> VISUAL_INTENTS [select,preview-layout,preview-style,inspect-meaning]
//   visual-theme.mjs  -> 6 presets, moods/textures/appearances/motions/densities

