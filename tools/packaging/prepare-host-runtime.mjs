#!/usr/bin/env node
// Explicit G Windows packaging gate, not an installer or publication mechanism.
//
// Frozen packaging contract (the only thing this gate is allowed to stage):
//   * the product payload is exactly STAGED_DIRS + STAGED_TOP_FILES + the
//     PACKAGED_BINARIES + the bundled node.exe;
//   * the staged runtime must launch every required binary from those files
//     alone - never Cargo, Bun or Git, and never a debug build;
//   * the staged tree is frozen into a sha256 manifest so an installed runtime
//     can be re-verified byte for byte after the fact.
import {existsSync,lstatSync,readFileSync,cpSync,copyFileSync,mkdirSync,renameSync,rmSync,writeFileSync,readdirSync} from 'node:fs';
import path from 'node:path';
import {fileURLToPath,pathToFileURL} from 'node:url';
import {spawnSync} from 'node:child_process';
import {createHash} from 'node:crypto';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../..');
const resources=path.join(root,'src-tauri','resources');
const runtime=path.join(resources,'runtime');
const stage=path.join(resources,'.runtime-stage-'+process.pid);
const previous=path.join(resources,'.runtime-previous-'+process.pid);
// One canonical frozen payload packager. The GPUI destination is intentionally
// independent of Tauri's resource directory; no duplicate staging engine.
export function stagingPaths(mode) {
 const resourceRoot=mode==='--stage-gpui'
   ? path.join(root,'native','gpui-desktop','resources')
   : resources;
 return {
   resources:resourceRoot,
   runtime:path.join(resourceRoot,'runtime'),
   stage:path.join(resourceRoot,'.runtime-stage-'+process.pid),
   previous:path.join(resourceRoot,'.runtime-previous-'+process.pid)
 };
}
// Frozen staging contract. STAGED_DIRS are workspace trees copied verbatim;
// STAGED_TOP_FILES are single product files the Host reads at runtime.
export const STAGED_DIRS=['apps/vivim-host','apps/mobile-relay','studio','harness','hq','packages/tierflow','packages/vec-ui-engines','contracts'];
export const STAGED_TOP_FILES=['package.json','bun.lock','integration/source-lock.json','docs/data-intelligence/ingress-registry.v1.json'];
// A frozen package needs both lockfiles. They are generated by the W01-G gate
// and promoted by the owner; until then a clean checkout is NOT packageable.
export const LOCKFILES=['bun.lock','Cargo.lock'];
// Only these native binaries have a proven production port in the shipped
// product. `hqkg-import` is the native KG importer behind `hq kg sync`
// (hq/bin/hq.mjs:1075) and the refresh pipeline (hq/lib/refresh.mjs:313); it
// must be staged before those call sites can drop their Cargo spawn, or product
// KG sync regresses.
export const PACKAGED_BINARIES=['hqkg-personal','hqkg-chat-context','hqkg-web-feed','hqkg-import','hqkg-development','vivim-program-validate','vivim-vec-project','vivim-product-pure','vivim-private-shares'];
// Release build plan for the packaged binaries. A name in PACKAGED_BINARIES that
// is not built here could only come from a debug target tree, so the two lists
// are asserted against each other by scripts/batch-evidence/D05-packaging.test.mjs.
export const CARGO_BUILDS=[
 {package:'hq-knowledge-graph',features:['importer','native-program'],
  bins:['hqkg-personal','hqkg-chat-context','hqkg-web-feed','hqkg-import','hqkg-development']},
 {package:'vivim-programmability-core',features:[],bins:['vivim-program-validate','vivim-vec-project','vivim-product-pure']},
 {package:'vivim-private-shares',features:[],bins:['vivim-private-shares']}];
export function cargoArgs(plan,targetDir){
 const args=['build','--release','-p',plan.package];
 if(plan.features?.length)args.push('--features',plan.features.join(','));
 for(const bin of plan.bins)args.push('--bin',bin);
 return [...args,'--target-dir',targetDir];
}
// The Host entry point whose import closure the staged runtime must satisfy.
export const HOST_ENTRY='apps/vivim-host/server.mjs';
export const RUNTIME_MANIFEST_NAME='runtime.manifest.json';
export const RUNTIME_MANIFEST_SCHEMA='arbor.host-runtime-manifest/1';
export const RUNTIME_PLACEHOLDER='ARBOR-RUNTIME-PLACEHOLDER.txt';
const dirs=STAGED_DIRS;
const topFiles=STAGED_TOP_FILES;
const refuse=s=>{throw new Error('PACKAGING_REFUSED: '+s);};
function checkInputs({requireLock=true,requireTauri=true}={}){
 const required=[...topFiles.filter(p=>requireLock||p!=='bun.lock'),
   ...(requireTauri?['src-tauri/tauri.conf.json']:[]),...dirs];
 for(const p of required)if(!existsSync(path.join(root,p)))refuse('missing '+p);
 if(requireTauri){
  const c=JSON.parse(readFileSync(path.join(root,'src-tauri/tauri.conf.json'),'utf8'));
  for(const p of Object.keys(c.bundle?.resources||{}))if(/\.apk$/i.test(p))refuse('PWA-first still mandates APK: '+p);
  if(!Object.keys(c.bundle?.resources||{}).includes('resources/runtime/'))refuse('Missing required resources/runtime/ in Tauri config');
 }
}
const forbidden=name=>/(^\.env(?:\.|$)|owner-token|\.sqlite(?:3)?(?:-|$|\.)|\.db$|\.pem$|\.p12$|\.key$|\.log$|\.tap$|\.zip$|\.apk$|\.exe$)/i.test(name);
const excluded=new Set(['.git','node_modules','target','coverage','test','tests','fixtures','.cache','dist']);
function safeFilter(p){
 const name=path.basename(p),s=lstatSync(p);
 if(s.isSymbolicLink())refuse('Symlink in runtime input: '+p);
 if(forbidden(name))refuse('Potential private/binary artifact: '+p);
 return !s.isDirectory()||!excluded.has(name);
}
function run(exe,args,cwd){
 const r=spawnSync(exe,args,{cwd,encoding:'utf8',timeout:600000,windowsHide:true});
 if(r.error||r.status!==0)refuse(exe+' '+args.join(' ')+' exit='+String(r.status??'N/A')+': '+(r.error?.message||r.stderr?.slice(-2000)||''));
 return r.stdout.trim();
}
function nodeBinary(){
 if(process.platform!=='win32')refuse('Actual Windows runner required');
 const p=process.env.ARBOR_NODE24_EXE,hash=process.env.ARBOR_NODE24_SHA256?.toLowerCase();
 if(!p||!path.isAbsolute(p)||!existsSync(p)||path.basename(p).toLowerCase()!=='node.exe')refuse('Set ARBOR_NODE24_EXE to absolute Windows node.exe');
 if(!hash||!/^[0-9a-f]{64}$/.test(hash))refuse('Set verified 64-hex ARBOR_NODE24_SHA256');
 const actual=createHash('sha256').update(readFileSync(p)).digest('hex');
 if(actual!==hash)refuse('Node SHA256 mismatch expected='+hash+' actual='+actual);
 const meta=JSON.parse(run(p,['-p','JSON.stringify({node:process.versions.node,platform:process.platform,arch:process.arch})'],root));
 if(meta.platform!=='win32'||meta.arch!=='x64'||Number(meta.node.split('.')[0])<24)refuse('Expected signed Node 24+ Windows x64: '+JSON.stringify(meta));
 const cmd="$s=Get-AuthenticodeSignature -LiteralPath '"+p.replaceAll("'","''")+"'; if ($s.Status -ne 'Valid') { Write-Error $s.Status; exit 41 }";
 const sig=spawnSync('powershell.exe',['-NoProfile','-NonInteractive','-EncodedCommand',Buffer.from(cmd,'utf16le').toString('base64')],{encoding:'utf8',windowsHide:true});
 if(sig.error||sig.status!==0)refuse('Node Authenticode invalid exit='+String(sig.status??'N/A')+': '+(sig.stderr||sig.error?.message||''));
 return p;
}
// ---------------------------------------------------------------------------
// Frozen manifest, runtime closure and installed-runtime verification.
//
// These are the parts of the gate that can be exercised without a Windows
// signing identity, a native toolchain or a device, so they are exported and
// unit tested. The gate itself stays fail-closed: every check below reports a
// problem instead of repairing anything.
// ---------------------------------------------------------------------------

// The Tauri build script resolves every declared bundle resource path at
// compile time. `resources/runtime/` is a generated directory, so a clean
// checkout has no such directory and `cargo build -p vivim-host` fails with
// "resource path 'resources\runtime' doesn't exist". Ensuring the directory
// exists (with a marker that says it is generated) is what makes the owning
// build work from a clean checkout; `--stage` replaces it with the real tree.
export function ensureRuntimeResourceDir(base=root){
 const dir=path.join(base,'src-tauri','resources','runtime');
 if(!existsSync(dir))mkdirSync(dir,{recursive:true});
 const marker=path.join(dir,RUNTIME_PLACEHOLDER);
 if(!existsSync(marker))writeFileSync(marker,[
  'ARBOR generated packaged-runtime placeholder.',
  '',
  'This directory exists only so the Tauri build script can resolve the',
  'declared resource path "resources/runtime/" on a clean checkout.',
  'tools/packaging/prepare-host-runtime.mjs --stage replaces it with the real',
  'frozen runtime. A tree that still contains this marker is NOT a package.',
  ''].join('\n'));
 return dir;
}

// Relative-import closure of a source file, resolved inside `base`.
function resolveRelative(fromFile,specifier,base){
 const target=path.resolve(path.dirname(fromFile),specifier);
 if(!(target===base||target.startsWith(base+path.sep)))return null;
 const probes=[target,
  ...['.mjs','.js','.cjs','.ts','.tsx','.json'].map(e=>target+e),
  ...['index.mjs','index.js','index.ts'].map(n=>path.join(target,n))];
 return probes.find(c=>{try{return existsSync(c)&&lstatSync(c).isFile();}catch{return false;}})??null;
}
export function importClosure(entryFile,base,{unresolved=null}={}){
 const seen=new Set(),queue=[entryFile];
 while(queue.length){
  const file=queue.pop();
  if(seen.has(file))continue;
  seen.add(file);
  let source='';
  try{source=readFileSync(file,'utf8');}catch{continue;}
  const patterns=[
   /(?:^|\n)\s*import\s+(?:[\s\S]*?\s+from\s+)?['"](\.[^'"]+)['"]/g,
   /(?:^|\n)\s*export\s+[\s\S]*?\s+from\s+['"](\.[^'"]+)['"]/g,
   /\bimport\s*\(\s*['"](\.[^'"]+)['"]\s*\)/g,
   /\brequire\s*\(\s*['"](\.[^'"]+)['"]\s*\)/g];
  for(const pattern of patterns)for(const match of source.matchAll(pattern)){
   const resolved=resolveRelative(file,match[1],base);
   if(resolved&&!resolved.includes(path.sep+'node_modules'+path.sep))queue.push(resolved);
   else if(!resolved&&unresolved){
    const sourcePath=path.relative(base,file).split(path.sep).join('/');
    unresolved.add(sourcePath+' -> '+match[1]);
   }
  }
 }
 return seen;
}
// Repo-relative POSIX paths the Host loads at runtime through relative imports.
export function runtimeImportClosure(base=root,entry=HOST_ENTRY){
 const entryFile=path.join(base,entry);
 if(!existsSync(entryFile))return [];
 return [...importClosure(entryFile,base)]
  .map(f=>path.relative(base,f).split(path.sep).join('/'))
  .sort();
}
/// Source closure can be incomplete even when all the existing visited files
/// look healthy: the old scanner silently ignored unresolved relative imports.
/// Keep this a read-only scan of the *actual staged Host* entrypoint.
export function runtimeImportProblems(base=root,entry=HOST_ENTRY){
 const entryFile=path.join(base,entry);
 if(!existsSync(entryFile))return ['Host entry not present: '+entry];
 const unresolved=new Set();
 importClosure(entryFile,base,{unresolved});
 return [...unresolved].sort();
}
// True when a repo-relative path is inside the frozen staged payload.
export function stagedCoverage(rel){
 if(STAGED_TOP_FILES.includes(rel))return true;
 return STAGED_DIRS.some(d=>rel===d||rel.startsWith(d+'/'));
}
// Closure members the frozen staged payload would not carry into the package.
export function uncoveredClosure(rels){
 return rels.filter(rel=>!stagedCoverage(rel));
}
// sha256 manifest of the product payload (installed dependencies excluded:
// their integrity comes from the frozen bun.lock, not from a file list).
export function frozenManifest(base){
 const entries=[];
 const walk=(dir,prefix)=>{
  for(const name of readdirSync(dir).sort()){
   if(name==='node_modules'||name===RUNTIME_MANIFEST_NAME)continue;
   const abs=path.join(dir,name);
   let st;try{st=lstatSync(abs);}catch{continue;}
   if(st.isSymbolicLink())continue;
   if(st.isDirectory())walk(abs,prefix+name+'/');
   else entries.push({path:prefix+name,bytes:st.size,sha256:createHash('sha256').update(readFileSync(abs)).digest('hex')});
  }
 };
 walk(base,'');
 return {schema:RUNTIME_MANIFEST_SCHEMA,files:entries};
}
export function writeFrozenManifest(base){
 const manifest=frozenManifest(base);
 writeFileSync(path.join(base,RUNTIME_MANIFEST_NAME),JSON.stringify(manifest,null,2)+'\n');
 return manifest;
}
// Verify an installed or staged runtime tree against the frozen contract.
export function verifyStagedRuntime(base,{manifest=null,requireManifest=false}={}){
 const problems=[];
 if(requireManifest&&!manifest)problems.push('missing frozen runtime manifest');
 if(requireManifest&&!existsSync(path.join(base,RUNTIME_MANIFEST_NAME)))
   problems.push('missing installed runtime.manifest.json');
 // A source-only preflight is intentionally backwards-compatible; installed
 // runtime acceptance must require the actual Host entrypoint.
 if(requireManifest&&!existsSync(path.join(base,HOST_ENTRY)))
   problems.push('missing Host entry point: '+HOST_ENTRY);
 if(existsSync(path.join(base,RUNTIME_PLACEHOLDER)))
   problems.push('runtime still contains the generated Tauri resource placeholder');
 const rel=p=>path.relative(base,p).split(path.sep).join('/');
 for(const dir of STAGED_DIRS)if(!existsSync(path.join(base,dir)))problems.push('missing staged dir: '+dir);
 for(const file of STAGED_TOP_FILES)if(!existsSync(path.join(base,file)))problems.push('missing staged file: '+file);
 const closure=runtimeImportClosure(base);
 for(const file of closure)if(!existsSync(path.join(base,file)))problems.push('missing runtime closure file: '+file);
 if(requireManifest)for(const missing of runtimeImportProblems(base))
   problems.push('missing runtime relative import: '+missing);
 if(!existsSync(path.join(base,'node.exe')))problems.push('missing bundled node.exe');
 const binDir=path.join(base,'native','bin');
 for(const name of PACKAGED_BINARIES){
  const file=path.join(binDir,name+'.exe');
  if(!existsSync(file))problems.push('missing staged native binary: native/bin/'+name+'.exe');
  else {try{if(lstatSync(file).isSymbolicLink())problems.push('staged native binary is a symlink: '+rel(file));}catch{}}
 }
 if(existsSync(binDir))for(const name of readdirSync(binDir)){
  const stem=name.replace(/\.exe$/i,'');
  if(!PACKAGED_BINARIES.includes(stem))problems.push('unapproved file in native/bin: '+name);
 }
 // No debug fallback: a cargo target tree must never reach the package.
 for(const dir of ['target','native/hqkg/target'])if(existsSync(path.join(base,dir)))problems.push('runtime contains a cargo target directory (debug fallback): '+dir);
 // No Cargo/Bun/Git at runtime: the product payload may not ship those tools.
 const toolPattern=/^(cargo|bun|git)(\.exe)?$/i;
 const scan=(dir,prefix)=>{
  let names;try{names=readdirSync(dir);}catch{return;}
  for(const name of names){
   if(name==='node_modules')continue;
   const abs=path.join(dir,name);
   let st;try{st=lstatSync(abs);}catch{continue;}
   if(st.isSymbolicLink())continue;
   if(st.isDirectory())scan(abs,prefix+name+'/');
   else if(toolPattern.test(name))problems.push('runtime ships a build tool: '+prefix+name);
  }
 };
 scan(base,'');
 // Frozen manifest: a verified install must contain exactly the files in the
 // canonical manifest (apart from installed dependency contents, whose
 // integrity is governed separately by the frozen bun.lock).
 let verifiedFiles=0;
 if(manifest){
  if(manifest.schema!==RUNTIME_MANIFEST_SCHEMA)
   problems.push('unexpected runtime manifest schema: '+String(manifest.schema));
  if(!Array.isArray(manifest.files))
   problems.push('invalid runtime manifest files array');
  const expected=new Set(),caseInsensitivePaths=new Set();
  const validRel=rel=>typeof rel==='string'&&rel.length>0&&
   !rel.includes('\\')&&!rel.includes(':')&&!rel.startsWith('/')&&
   rel.split('/').every(part=>part.length>0&&part!=='.'&&part!=='..');
  for(const entry of Array.isArray(manifest.files)?manifest.files:[]){
   const p=entry?.path;
   if(!validRel(p)){problems.push('invalid manifest path: '+String(p));continue;}
   if(expected.has(p)){problems.push('duplicate manifest file: '+p);continue;}
   const folded=p.toLowerCase();
   if(caseInsensitivePaths.has(folded)){
     problems.push('case-colliding manifest file on Windows: '+p);
     continue;
   }
   caseInsensitivePaths.add(folded);
   expected.add(p);
   if(!Number.isSafeInteger(entry.bytes)||entry.bytes<0||
      typeof entry.sha256!=='string'||!/^[0-9a-f]{64}$/.test(entry.sha256)){
    problems.push('invalid manifest file metadata: '+p);continue;
   }
   const abs=path.join(base,...p.split('/'));
   if(!existsSync(abs)){problems.push('manifest file missing from runtime: '+p);continue;}
   const st=lstatSync(abs);
   if(!st.isFile()){problems.push('manifest entry is not a regular file: '+p);continue;}
   if(st.size!==entry.bytes){
    problems.push('runtime file size does not match the frozen manifest: '+p);
    continue;
   }
   const actual=createHash('sha256').update(readFileSync(abs)).digest('hex');
   if(actual!==entry.sha256)problems.push('runtime file does not match the frozen manifest: '+p);
   else verifiedFiles++;
  }
  const walk=(dir,prefix)=>{
   for(const name of readdirSync(dir)){
    if(name==='node_modules'||name===RUNTIME_MANIFEST_NAME)continue;
    const abs=path.join(dir,name),p=prefix+name;
    const st=lstatSync(abs);
    if(st.isSymbolicLink()){problems.push('symlink in frozen runtime: '+p);continue;}
    if(st.isDirectory())walk(abs,p+'/');
    else if(!expected.has(p))problems.push('unlisted file in frozen runtime: '+p);
   }
  };
  walk(base,'');
 }
 return {ok:problems.length===0,problems,checks:{
  stagedDirs:STAGED_DIRS.length,stagedFiles:STAGED_TOP_FILES.length,
  packagedBinaries:PACKAGED_BINARIES.length,runtimeClosureFiles:closure.length,
  manifestFilesVerified:verifiedFiles}};
}

export function main(argv){
const mode=argv[0]||'--check';
if(!['--check','--prepare','--verify','--stage','--stage-gpui','--lock'].includes(mode))refuse('Usage: node tools/packaging/prepare-host-runtime.mjs --check|--prepare|--verify [--dir <runtime>]|--stage|--stage-gpui|--lock');
const rest=argv.slice(1);
const usage='Usage: node tools/packaging/prepare-host-runtime.mjs --check|--prepare|--verify [--dir <runtime>]|--stage|--stage-gpui|--lock';
if(mode==='--verify'){
 if(rest.length!==0&&!(rest.length===2&&rest[0]==='--dir'&&rest[1]))
  refuse(usage);
 const base=rest.length===2?path.resolve(process.cwd(),rest[1]):runtime;
 if(!existsSync(base)){console.log(JSON.stringify({ok:false,problems:['runtime tree not found: '+base],checks:{}}));process.exit(2);}
 const manifestPath=path.join(base,RUNTIME_MANIFEST_NAME);
 const manifest=existsSync(manifestPath)?JSON.parse(readFileSync(manifestPath,'utf8')):null;
 const report=verifyStagedRuntime(base,{manifest,requireManifest:true});
 console.log(JSON.stringify({status:report.ok?'RUNTIME_VERIFIED':'RUNTIME_INVALID',runtime:base,...report}));
 process.exit(report.ok?0:1);
}
if(rest.length)refuse(usage);
if(mode==='--prepare'){
 // The declared Tauri resource path must exist before the owning build runs.
 const dir=ensureRuntimeResourceDir(root);
 console.log(JSON.stringify({status:'RUNTIME_RESOURCE_DIR_ENSURED',runtime:dir,note:'Generated placeholder only; --stage replaces it with the frozen runtime'}));
}else{
if(mode==='--lock'){
 // Explicit developer step, never replace the frozen distribution install with a floating install.
 run('bun',['install','--lockfile-only','--ignore-scripts'],root);
 checkInputs();
 console.log(JSON.stringify({status:'LOCK_GENERATED',note:'Review and commit bun.lock before staging'}));
}else if(mode==='--check'){
 // Preflight also guarantees the declared Tauri resource path resolves, so the
 // owning build (`cargo check -p vivim-host`) works from a clean checkout.
 checkInputs({requireLock:false});
 const dir=ensureRuntimeResourceDir(root);
 const missingLocks=LOCKFILES.filter(p=>!existsSync(path.join(root,p)));
 console.log(JSON.stringify({status:'SOURCE_PREFLIGHT_ONLY',runtime:'NOT_STAGED',runtimeResourceDir:dir,
  missingLockfiles:missingLocks,pwaFirst:true,apk:'DEFERRED',
  note:'No build or binary trust acceptance implied; a missing lockfile blocks --stage'}));
 if(missingLocks.length>0)process.exit(1);
}else{
const location=stagingPaths(mode);
const targetRuntime=location.runtime, targetStage=location.stage, targetPrevious=location.previous;
if(mode==='--stage-gpui')mkdirSync(location.resources,{recursive:true});
checkInputs({requireLock:true,requireTauri:mode!=='--stage-gpui'});
 const binary=nodeBinary();
 if(existsSync(targetStage)||existsSync(targetPrevious))refuse('Existing staging/rollback directory requires manual inspection');
 mkdirSync(targetStage,{recursive:true});
 try{
  for(const p of dirs){const to=path.join(targetStage,p);mkdirSync(path.dirname(to),{recursive:true});cpSync(path.join(root,p),to,{recursive:true,filter:safeFilter});}
  for(const p of topFiles){const to=path.join(targetStage,p);mkdirSync(path.dirname(to),{recursive:true});copyFileSync(path.join(root,p),to);}
  copyFileSync(binary,path.join(targetStage,'node.exe'));
  // Build and targetStage the existing Rust CLIs once at packaging time. The Host
  // discovers these exact bundled executables without Cargo or environment at targetRuntime.
  for(const plan of CARGO_BUILDS)run('cargo',cargoArgs(plan,path.join(root,'target')),root);
 const nativeDir=path.join(targetStage,'native','bin');
  mkdirSync(nativeDir,{recursive:true});
  for(const name of PACKAGED_BINARIES)
    copyFileSync(path.join(root,'target','release',name+'.exe'),path.join(nativeDir,name+'.exe'));
  run('bun',['install','--production','--frozen-lockfile','--ignore-scripts'],targetStage);
  run(path.join(targetStage,'node.exe'),['--check',path.join(targetStage,'apps/vivim-host/server.mjs')],targetStage);
  // Freeze the staged payload and verify it before it replaces the live targetRuntime.
  writeFrozenManifest(targetStage);
  const report=verifyStagedRuntime(targetStage,{manifest:JSON.parse(readFileSync(path.join(targetStage,RUNTIME_MANIFEST_NAME),'utf8')),requireManifest:true});
  if(!report.ok)refuse('staged targetRuntime failed verification: '+report.problems.join('; '));
  if(existsSync(targetRuntime))renameSync(targetRuntime,targetPrevious);
  try{renameSync(targetStage,targetRuntime);}catch(e){if(existsSync(targetPrevious))renameSync(targetPrevious,targetRuntime);throw e;}
  if(existsSync(targetPrevious))rmSync(targetPrevious,{recursive:true,force:true});
  console.log(JSON.stringify({status:'STAGED_NOT_ACCEPTED',runtime:targetRuntime,nodeSha256:process.env.ARBOR_NODE24_SHA256,apk:'DEFERRED',
   manifestFiles:report.checks.manifestFilesVerified,runtimeClosureFiles:report.checks.runtimeClosureFiles,
   note:'Cargo/Bun/security/device acceptance still required'}));
 }catch(e){if(existsSync(targetStage))rmSync(targetStage,{recursive:true,force:true});throw e;}
}
}
}

// Run only when executed directly, so the gate can be imported and unit tested
// without touching the working tree.
if(process.argv[1]&&pathToFileURL(process.argv[1]).href===import.meta.url)main(process.argv.slice(2));
