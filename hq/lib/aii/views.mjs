// hq/lib/aii/views.mjs — deterministic coverage views for the AII registry.
//
// The old buildViews() embedded `generatedAt` in the JSON and rendered the
// Markdown from the same object, so two runs over identical evidence produced
// different bytes and no one could tell whether coverage had actually moved.
//
// Here the view is a pure function of its inputs:
//
//   coverageView({ reg, sum, evidence, plan, run, mode, generatedAt })
//
// `generatedAt` is the only non-deterministic field and it is excluded from
// viewDigest(). Everything else — including the run summary and the evidence
// binding of every scenario — is reproducible.
//
// Schema hq.aii-coverage/2 keeps the hq.aii-coverage/1 `.summary.gate` shape
// that docs/AII-METRICS-DASHBOARD.md reads, and adds `evidence` + `run`.

import { canonicalJson } from '../util.mjs';
import { sha256Text } from './plan.mjs';
import { viewAiiCoverage } from './registry.mjs';
import { summarizeEvidence } from './receipts-policy.mjs';

export const AII_COVERAGE_SCHEMA = 'hq.aii-coverage/2';

const EVIDENCE_STATES = ['verified', 'stale', 'legacy', 'foreign', 'failed', 'absent'];

function failureRow(result) {
  return {
    id: result.id,
    relPath: result.relPath,
    status: result.status,
    problem: result.problem ?? null,
    error: result.error ?? null,
    missing: Array.isArray(result.missing) ? result.missing : [],
  };
}

/**
 * coverageView — the JSON payload written to hq/aii/coverage.json.
 * Also used in-memory for --summary output, so it must not touch the disk.
 */
export function coverageView({
  reg,
  sum,
  evidence = null,
  plan = null,
  run = null,
  mode = 'summary',
  generatedAt = null,
} = {}) {
  const rows = viewAiiCoverage(reg).map((row) => {
    const bound = evidence instanceof Map ? evidence.get(row.id) : null;
    return {
      ...row,
      evidenceState: bound?.state ?? 'unknown',
      evidenceReason: bound?.reason ?? null,
      evidenceEligible: Boolean(bound?.eligible),
      evidenceReceipt: bound?.receipt ?? null,
      fixture: bound?.canonical ?? null,
    };
  });

  const failures = (run?.failures ?? []).map(failureRow).sort((a, b) => a.id.localeCompare(b.id) || a.relPath.localeCompare(b.relPath));
  const view = {
    schema: AII_COVERAGE_SCHEMA,
    generatedAt: generatedAt ?? new Date().toISOString(),
    mode,
    catalog: {
      path: 'docs/AII-CATALOG.md',
      sha256: plan?.catalogSha ?? null,
    },
    plan: plan
      ? {
        digest: plan.digest ?? null,
        files: plan.counts?.files ?? null,
        uniqueIds: plan.counts?.uniqueIds ?? null,
        byTier: plan.counts?.byTier ?? null,
        byRole: plan.counts?.byRole ?? null,
        duplicates: plan.duplicates ?? [],
      }
      : null,
    summary: {
      total: sum.total,
      byStatus: sum.byStatus,
      coverage: sum.coverage,
      terminal: sum.terminal,
      gate: sum.gate,
    },
    evidence: evidence ? summarizeEvidence(evidence) : null,
    evidenceStates: EVIDENCE_STATES,
    scenarios: rows,
    run: run
      ? {
        at: run.at ?? null,
        mode: run.mode ?? mode,
        jobs: run.jobs ?? 1,
        ran: run.ran ?? 0,
        passed: run.passed ?? 0,
        failed: run.failed ?? 0,
        elapsedMs: run.elapsedMs ?? null,
        budgetExhausted: run.budgetExhausted ?? false,
        probeCacheHits: run.probeCacheHits ?? 0,
        failures,
      }
      : null,
    // Compatibility alias: hq.aii-coverage/1 exposed `lastRun` with the same
    // failure rows. Keep it so existing readers do not break on the bump.
    lastRun: run
      ? { at: run.at ?? null, ran: run.ran ?? 0, passed: run.passed ?? 0, failures }
      : null,
  };
  view.digest = viewDigest(view);
  return view;
}

/** viewDigest — stable over everything except the generation timestamp. */
export function viewDigest(view) {
  const { generatedAt, digest, ...stable } = view ?? {};
  return sha256Text(canonicalJson(stable));
}

function statusCell(row) {
  if (row.status === 'covered_verified') return `covered_verified (${row.receiptId})`;
  if (row.status === 'out_of_scope') return 'out_of_scope';
  return row.status;
}

function evidenceBadge(row) {
  if (row.evidenceState === 'verified') return 'verified';
  if (row.evidenceState === 'stale') return 'stale';
  return row.evidenceState;
}

/** renderCoverageMarkdown — docs/AII-COVERAGE.md. */
export function renderCoverageMarkdown(view) {
  const sum = view.summary;
  const rows = view.scenarios;
  const lines = [];
  lines.push('# AII Coverage (generated)');
  lines.push('');
  lines.push('<!-- Generated by scripts/aii-verify.mjs — a pure function of');
  lines.push('     hq/aii/assessments/*.json + aii-fixture receipts in .hq/index.db');
  lines.push('     + the run journal hq/aii/run-journal.json.');
  lines.push('     Do not hand-edit; regenerate instead. Catalog: docs/AII-CATALOG.md -->');
  lines.push('');
  lines.push(`- schema: \`${view.schema}\` · generated: ${view.generatedAt} · mode: ${view.mode} · digest: \`${String(view.digest).slice(0, 12)}\``);
  lines.push(`- coverage: **${sum.terminal}/${sum.total}** (${sum.byStatus.covered_verified} covered_verified + ${sum.byStatus.out_of_scope} out_of_scope)`);
  lines.push(`- release gate (P0): **${sum.gate.terminal}/${sum.gate.total}** terminal${sum.gate.open.length ? ` — open: ${sum.gate.open.join(', ')}` : ''}`);
  lines.push(`- by status: ${Object.entries(sum.byStatus).filter(([, n]) => n > 0).map(([k, n]) => `${k}=${n}`).join(' · ')}`);
  if (view.evidence) {
    lines.push(`- evidence binding: ${Object.entries(view.evidence).filter(([k]) => EVIDENCE_STATES.includes(k)).map(([k, n]) => `${k}=${n}`).join(' · ')}`);
  }
  if (view.plan) {
    lines.push(`- fixtures: ${view.plan.files} file(s) for ${view.plan.uniqueIds} scenario id(s) · tiers ${Object.entries(view.plan.byTier ?? {}).map(([k, n]) => `${k}=${n}`).join(' · ')}`);
  }
  lines.push('');
  lines.push('| ID | P | Group | Status | Evidence | Binding | Receipt / rationale |');
  lines.push('| --- | --- | --- | --- | --- | --- | --- |');
  for (const r of rows) {
    const receipt = r.status === 'covered_verified'
      ? r.receiptId
      : (r.outOfScopeRationale ? 'out of scope — see ruling below' : (r.gap ? `gap → ${r.gap.engine}` : ''));
    lines.push(`| ${r.id} | ${r.priority} | ${r.group} | ${statusCell(r)} | ${r.evidence.length} | ${evidenceBadge(r)} | ${receipt} |`);
  }

  const oos = rows.filter((r) => r.status === 'out_of_scope');
  if (oos.length) {
    lines.push('');
    lines.push('## Out-of-scope rulings (conceptual)');
    for (const r of oos) lines.push(`- **${r.id}** — ${r.outOfScopeRationale} (assessed by ${r.assessedBy ?? 'unknown'} at ${r.assessedAt ?? 'unknown'})`);
  }
  const gaps = rows.filter((r) => r.status === 'gap');
  if (gaps.length) {
    lines.push('');
    lines.push('## Open gaps');
    for (const r of gaps) lines.push(`- **${r.id}** — ${r.gap.capability} · engine: ${r.gap.engine} · effort: ${r.gap.effort} · fixture: ${r.gap.fixtureSketch}`);
  }

  const unproven = rows.filter((r) => r.status === 'covered_verified' && r.evidenceState !== 'verified');
  if (unproven.length) {
    lines.push('');
    lines.push('## Receipts not bound to current fixture bytes');
    lines.push('');
    lines.push('These scenarios are still terminal, but their proof predates the current fixture file.');
    lines.push('They count under the default policy and are excluded by `--strict`.');
    for (const r of unproven) lines.push(`- **${r.id}** — ${r.evidenceState}: ${r.evidenceReason ?? 'no detail'} · \`${r.fixture ?? 'no fixture'}\``);
  }

  if (view.run && view.run.failures.length) {
    lines.push('');
    lines.push('## Last-run fixture failures');
    for (const f of view.run.failures) {
      lines.push(`- **${f.id}** (${f.status}${f.problem && f.problem !== f.status ? `/${f.problem}` : ''}) ${f.error ?? ''}${f.missing?.length ? ` missing: ${f.missing.map((m) => m.what).join(' | ')}` : ''}`);
    }
  }
  return lines.join('\n') + '\n';
}

/** summaryLines — the two console lines the dashboard and CLIs have always read. */
export function summaryLines(view) {
  const sum = view.summary;
  const byStatus = Object.entries(sum.byStatus).filter(([, n]) => n > 0).map(([k, n]) => `${k}=${n}`).join(' · ');
  const out = [
    `aii-verify: coverage ${sum.terminal}/${sum.total} (${(sum.coverage * 100).toFixed(0)}%) · gate P0 ${sum.gate.terminal}/${sum.gate.total}`,
    `aii-verify: by status ${byStatus}`,
  ];
  if (view.evidence) {
    out.push(`aii-verify: evidence ${EVIDENCE_STATES.map((s) => `${s}=${view.evidence[s] ?? 0}`).join(' · ')}`);
  }
  return out;
}
